import { tmpdir } from 'node:os'
import { createApp } from '../src/app'
import { createServices } from '../src/config/services'
import { readConfig } from '../src/config/env'
import { PrivateFilesystem } from '../src/storage/filesystem'
import { PrivateR2 } from '../src/storage/objects'

const config = readConfig()
// Each storage backend registers a different private-asset route, so the inventory is built from
// both adapters rather than from whichever backend this machine happens to have configured.
// Neither construction touches the network or the filesystem.
const stores = [
  new PrivateFilesystem(`${tmpdir()}/erect3d-endpoint-inventory`, 'inventory-only-secret'),
  new PrivateR2({
    ...config,
    R2_ENDPOINT: 'https://inventory.invalid',
    R2_BUCKET: 'inventory-only',
    R2_ACCESS_KEY_ID: 'inventory-only',
    R2_SECRET_ACCESS_KEY: 'inventory-only-secret',
  }),
]
const routes = new Set<string>()
for (const store of stores) {
  const services = createServices(config, { store })
  for (const route of createApp(services).routes)
    if (route.method !== 'ALL' && !route.path.includes('*')) routes.add(`${route.method} ${route.path}`)
  services.limits.close()
  await services.db.close()
}
await Bun.write(
  new URL('../docs/ENDPOINTS.md', import.meta.url),
  `# Registered endpoints

Generated by \`bun scripts/endpoint-inventory.ts\` from the Hono route tree, with both private
storage backends registered so the list does not depend on local credentials.

${[...routes]
  .sort()
  .map((route) => `- \`${route}\``)
  .join('\n')}
`,
)
